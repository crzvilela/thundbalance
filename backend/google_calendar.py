def _trial_event_fields(full_name, email, phone, goal, experience, trainer_name, provisional):
    """Title, description and colour of a trial-session event.

    Provisional (approved, waiting for the client): "[Pendiente] Trial Session · Ana".
    Confirmed by the client: "Trial Session · Ana"."""
    first_name = (str(full_name or "").split() or [""])[0]
    title = f"[Pendiente] Trial Session · {first_name}" if provisional else f"Trial Session · {first_name}"
    state = "Pendiente de confirmación del cliente" if provisional else "Confirmada por el cliente"
    lines = [
        f"Estado: {state}",
        f"Cliente: {full_name}",
        f"Email: {email}",
        f"Teléfono: {phone}",
    ]
    if goal:
        lines.append(f"Objetivos: {goal}")
    if experience:
        lines.append(f"Experiencia: {experience}")
    if trainer_name:
        lines.append(f"Entrenador: {trainer_name}")
    # 5 = yellow while pending, 10 = green once confirmed
    return title, chr(10).join(lines), ("5" if provisional else "10")


