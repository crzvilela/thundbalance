def clear_calendar():

    service = get_calendar_service()

    events = service.events().list(
        calendarId=CALENDAR_ID
    ).execute()

    items = events.get("items", [])

    for event in items:

        try:

            service.events().delete(
                calendarId=CALENDAR_ID,
                eventId=event["id"]
            ).execute()

            print("Deleted:", event["id"])

        except Exception:

            pass

    print("GOOGLE CALENDAR CLEARED")


def list_calendar_events(time_min, time_max):
    """Events between two RFC3339 instants, in Europe/Madrid time.

    Recurring events are expanded and results are paginated until Google has
    no more pages, so a busy month is returned completely.
    """

    service = get_calendar_service()
    events = []
    page_token = None

    while True:
        response = service.events().list(
            calendarId=CALENDAR_ID,
            timeMin=time_min,
            timeMax=time_max,
            singleEvents=True,
            orderBy="startTime",
            timeZone="Europe/Madrid",
            maxResults=250,
            pageToken=page_token
        ).execute()

        events.extend(response.get("items", []))
        page_token = response.get("nextPageToken")

        if not page_token:
            return events
