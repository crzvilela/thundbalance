// Writes src/fonts.css: the @font-face rules of every font the site and the landing editor can use, served from our own files (@fontsource).
// The site never asks Google Fonts for anything. Only the Latin and Latin-extended parts are kept (English, Spanish, Catalan).
// To add a font: npm install --save-exact @fontsource-variable/<name> (or @fontsource/<name>), add it to FONTS below, run: node scripts/gen-fonts-css.mjs
// (the list of fonts the editor offers is FONT_OPTIONS in src/utils/fonts.js: a test checks that every one is here).
