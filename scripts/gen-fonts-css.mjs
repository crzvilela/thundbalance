const SUBSETS = ['latin', 'latin-ext']
// The per-weight files of fontsource carry no unicode-range. Without it the browser downloads BOTH parts of a font for any text; with it
// the Latin-extended part is fetched only when a character of that range is on the page (the standard ranges of the Google Fonts subsets).
const RANGES = {
  latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
  'latin-ext': 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF'
}
const blocksOf = (css) => css.match(/\/\*[^*]*\*\/\s*@font-face\s*\{[^}]*\}/g) || []

function rules([family, pkg, weights]) {
  const out = []
  const read = (file) => { try { return readFileSync(new URL(`../node_modules/${pkg}/${file}`, import.meta.url), 'utf8') } catch { return '' } }
  const files = weights === 'variable' ? [['wght.css', 'wght-normal']] : weights.flatMap(weight => SUBSETS.map(subset => [`${subset}-${weight}.css`, null]))
  for (const [file, suffix] of files) {
    for (const block of blocksOf(read(file))) {
      const name = block.match(/\/\*\s*([^*]+?)\s*\*\//)[1]
      if (suffix && !SUBSETS.some(subset => name.endsWith(`-${subset}-${suffix}`))) continue         // variable: only the Latin parts
      const subset = ['latin-ext', 'latin'].find(item => name.includes(`-${item}-`) || name.endsWith(`-${item}`))
      const withRange = block.includes('unicode-range') || !subset ? block : block.replace(/\}$/, `  unicode-range: ${RANGES[subset]};
}`)
      out.push(withRange
        .replace(/font-family:\s*'[^']+'/, `font-family: '${family}'`)
        .replace(/,\s*url\([^)]*\.woff\)\s*format\('woff'\)/g, '')                                  // no old woff copies
        .replace(/url\(\.\/files\/([^)]+)\)/g, `url('${pkg}/files/$1')`))
    }
  }
  if (!out.length) throw new Error(`no @font-face found for ${family} (${pkg})`)
  return out
}

const header = `/* GENERATED by scripts/gen-fonts-css.mjs: do not edit by hand.
   The fonts of the site and of the landing editor, served from our own files (@fontsource). Nothing is requested from Google Fonts, so the
   visitor's address is not sent to a third party when a page opens. Only the Latin and Latin-extended parts (English, Spanish, Catalan).
   The browser downloads a file only when a text on the page uses that font. */\n\n`
const css = FONTS.flatMap(font => rules(font)).join('\n\n')
writeFileSync(new URL('../src/fonts.css', import.meta.url), `${header}${css}\n`)
console.log(`${FONTS.length} fonts, ${css.split('@font-face').length - 1} rules`)
