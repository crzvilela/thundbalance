// Makes the WebP and AVIF copies of the images the site ships (public/site-images) and writes src/utils/siteImages.js (sizes of the originals).
//   node scripts/optimize-images.mjs
// Each JPG/PNG gets <name>.webp, <name>.avif and a 640-px wide pair (<name>-640.webp / -640.avif) for phones. The original stays as the
// fallback of <picture> (src/components/OptimizedPicture.jsx). Run it again when an image of public/site-images changes.
import { readdirSync, writeFileSync } from 'node:fs'
import { extname, join } from 'node:path'
import sharp from 'sharp'

const folder = new URL('../public/site-images/', import.meta.url)
const SMALL = 640
const manifest = {}

// .jpg before .png: hero.jpg is the current image, hero.png an old one with the same name (it keeps no copies)
const files = readdirSync(folder).sort((a, b) => (extname(a) === '.png') - (extname(b) === '.png') || a.localeCompare(b))
for (const file of files) {
  const extension = extname(file).toLowerCase()
  if (!['.jpg', '.jpeg', '.png'].includes(extension)) continue
  const name = file.slice(0, -extension.length)
  if (manifest[name]) continue                                          // the same name already done from a better source
  if (name.startsWith('logo')) continue                                // logos are small vector/flat images: left alone
  const source = join(folder.pathname.slice(1), file)
  const meta = await sharp(source).metadata()
  manifest[name] = { file, width: meta.width, height: meta.height, small: Math.min(SMALL, meta.width) }
  for (const [suffix, width] of [['', meta.width], [`-${SMALL}`, Math.min(SMALL, meta.width)]]) {
    const image = () => sharp(source).resize({ width, withoutEnlargement: true })
    await image().webp({ quality: 82, effort: 5 }).toFile(join(folder.pathname.slice(1), `${name}${suffix}.webp`))
    await image().avif({ quality: 55, effort: 5 }).toFile(join(folder.pathname.slice(1), `${name}${suffix}.avif`))
  }
  console.log(`${file}: ${meta.width}x${meta.height}`)
}

const body = `// GENERATED by scripts/optimize-images.mjs: do not edit by hand.\n// The images of public/site-images that have WebP / AVIF copies, with the size of the original (width and height avoid layout shift).\nexport const SITE_IMAGES = ${JSON.stringify(manifest, null, 2)}\n`
writeFileSync(new URL('../src/utils/siteImages.js', import.meta.url), body)
