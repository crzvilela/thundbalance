export function formText(language, key, values = {}) {
  const table = FORM_TEXT[language] || FORM_TEXT.en
  const text = table[key] ?? FORM_TEXT.en[key] ?? key
  return text.replace(/\{(\w+)\}/g, (_, name) => (values[name] ?? ''))
}

// A 422 from the server carries { code, field, message }: shown in the visitor's
// language when the code is known, otherwise the server's own message.
export function serverFieldError(detail, language) {
  if (!detail || typeof detail !== 'object' || !detail.code) return null
  const known = FORM_TEXT.en[detail.code]
  return { field: detail.field || '', message: known ? formText(language, detail.code) : String(detail.message || '') }
}
